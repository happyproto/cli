// Writes src/core/rust-escape-table.ts from test/fixtures/serde-json/escapes.txt, the code points
// Rust's Debug formatting prints as `\u{…}` (captured over every code point by the serde-json
// oracle, oracle/src/bin/escapes.rs). Rust decides that from its own Unicode tables
// (`is_grapheme_extended`, `is_printable`); a regex over `\p{…}` follows the JavaScript engine's,
// which differ between Node 22, Node 24 and Bun. Run after recapturing escapes.txt.
import { readFileSync, writeFileSync } from "node:fs";

const src = new URL("../test/fixtures/serde-json/escapes.txt", import.meta.url);
const out = new URL("../src/core/rust-escape-table.ts", import.meta.url);
const flat = [];
for (const line of readFileSync(src, "utf8").trim().split("\n")) {
  const [a, b] = line.split("-").map((h) => Number.parseInt(h, 16));
  flat.push(a, b);
}
const lines = [];
for (let i = 0; i < flat.length; i += 12) {
  lines.push(
    `  ${flat
      .slice(i, i + 12)
      .map((n) => `0x${n.toString(16)}`)
      .join(", ")},`,
  );
}
writeFileSync(
  out,
  `// Generated by scripts/gen-escape-table.mjs from test/fixtures/serde-json/escapes.txt; do not edit.
// Inclusive [first, last] ranges of the code points Rust's Debug formatting escapes as \`\\u{…}\`:
// \`is_grapheme_extended(c) || !is_printable(c)\`, by Rust's tables rather than the engine's.
export const RUST_ESCAPED: readonly number[] = [
${lines.join("\n")}
];
`,
);
console.log(`${flat.length / 2} ranges`);
