#!/usr/bin/env node
// The port's coverage ledger: every Rust test (#[test] / #[tokio::test] fn in
// crates/) against the TypeScript tests that carry its name (`it("name"` or
// `it.todo("name"`). Writes test/LEDGER.md. Run from the repo root. While the
// Rust crates exist it also writes test/rust-tests.json, the list of their
// tests; once they are removed, it reads that list instead.
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const walk = (d, ext) =>
  readdirSync(d).flatMap((f) => {
    const p = join(d, f);
    if (f === "target" || f === "node_modules") return [];
    return statSync(p).isDirectory() ? walk(p, ext) : p.endsWith(ext) ? [p] : [];
  });

const SNAPSHOT = "test/rust-tests.json";
const rust = new Map();
if (existsSync("crates")) {
  for (const f of walk("crates", ".rs")) {
    const text = readFileSync(f, "utf8");
    const names = [
      ...text.matchAll(/#\[(?:tokio::)?test[^\]]*\]\s*(?:#\[[^\]]*\]\s*)*(?:async\s+)?fn\s+(\w+)/g),
    ].map((m) => m[1]);
    if (names.length) rust.set(relative("crates", f), names);
  }
  const sorted = Object.fromEntries([...rust].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)));
  writeFileSync(SNAPSHOT, `${JSON.stringify(sorted, null, 2)}\n`);
} else {
  for (const [f, names] of Object.entries(JSON.parse(readFileSync(SNAPSHOT, "utf8")))) {
    rust.set(f, names);
  }
}
const ported = new Set();
const todo = new Set();
for (const f of walk("test", ".ts")) {
  const text = readFileSync(f, "utf8");
  for (const m of text.matchAll(/\bit(?:\.skipIf\([^)]*\))?\(\s*"([a-z0-9_]+)"/g)) ported.add(m[1]);
  for (const m of text.matchAll(/\bit\.todo\(\s*"([a-z0-9_]+)"/g)) todo.add(m[1]);
}
let total = 0;
let done = 0;
const rows = [];
for (const [file, names] of [...rust].sort()) {
  const p = names.filter((n) => ported.has(n)).length;
  total += names.length;
  done += p;
  rows.push(`| ${file} | ${names.length} | ${p} | ${names.filter((n) => todo.has(n)).length} |`);
}
const out = `# Test ledger\n\nRust tests ported to TypeScript by name: **${done} of ${total}**.\nGenerated by \`node scripts/ledger.mjs\`.\n\n| Rust file | Rust tests | Ported | Marked todo |\n|---|---|---|---|\n${rows.join("\n")}\n`;
writeFileSync("test/LEDGER.md", out);
console.log(`${done}/${total} Rust tests ported`);
